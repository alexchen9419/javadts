package game;

/**
 * 增益/減益效果分類枚舉
 *
 * 用於標識和分類不同類型的技能和效果。
 * 某些分類（如攻擊光環）有特殊的互斥規則。
 *
 * 互斥規則詳解：
 * - ATTACK_AURA：當同一實體擁有多個攻擊光環時，只有效果最強的會被應用
 * - 其他分類：多個效果都會被應用（無互斥限制）
 *
 * @author RuneRise Ability System
 */
public enum BuffCategory {
    /** 攻擊光環效果 - 提供攻擊力加成的光環技能
     *  互斥規則：同類型效果會進行互斥比較，只保留最強的 */
    ATTACK_AURA,
    
    /** 護盾效果 - 增加防禦者護盾值的技能 */
    SHIELD,
    
    /** 減益效果 - 對敵人產生負面影響的技能 */
    DEBUFF,
    
    /** 其他類型效果 - 不屬於上述分類的技能 */
    OTHER
}
